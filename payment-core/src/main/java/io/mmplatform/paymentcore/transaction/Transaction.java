package io.mmplatform.paymentcore.transaction;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.Id;
import jakarta.persistence.PostLoad;
import jakarta.persistence.PostPersist;
import jakarta.persistence.Table;
import jakarta.persistence.Transient;
import java.time.Instant;
import java.util.UUID;
import org.springframework.data.domain.Persistable;

/** A money movement request and its outcome. Immutable once persisted. */
@Entity
@Table(name = "transactions")
public class Transaction implements Persistable<UUID> {

    /**
     * Ids are generated by the application, so Spring Data cannot guess whether the
     * entity is new. Without this flag, save() would issue a useless SELECT (merge)
     * before every INSERT — measurable under load.
     */
    @Transient
    private boolean isNew = true;

    @Id
    private UUID id;

    @Column(name = "idempotency_key", nullable = false, unique = true, updatable = false, length = 64)
    private String idempotencyKey;

    @Column(name = "request_hash", nullable = false, updatable = false, length = 64)
    private String requestHash;

    @Enumerated(EnumType.STRING)
    @Column(name = "transaction_type", nullable = false, updatable = false, length = 16)
    private TransactionType type;

    @Enumerated(EnumType.STRING)
    @Column(nullable = false, length = 16)
    private TransactionStatus status;

    @Column(name = "source_account_id", nullable = false, updatable = false)
    private UUID sourceAccountId;

    @Column(name = "destination_account_id", nullable = false, updatable = false)
    private UUID destinationAccountId;

    @Column(nullable = false, updatable = false)
    private long amount;

    @Column(nullable = false, updatable = false)
    private long fee;

    @Column(nullable = false, updatable = false, length = 3)
    private String currency;

    @Column(name = "failure_reason", length = 64)
    private String failureReason;

    @Column(name = "occurred_at", nullable = false, updatable = false)
    private Instant occurredAt;

    @Column(name = "recorded_at", nullable = false, updatable = false)
    private Instant recordedAt;

    /** Required by JPA. */
    protected Transaction() {}

    private Transaction(String idempotencyKey, String requestHash, TransactionCommand command, long fee,
                        TransactionStatus status, FailureReason failureReason,
                        Instant occurredAt, Instant recordedAt) {
        this.id = UUID.randomUUID();
        this.idempotencyKey = idempotencyKey;
        this.requestHash = requestHash;
        this.type = command.type();
        this.sourceAccountId = command.sourceAccountId();
        this.destinationAccountId = command.destinationAccountId();
        this.amount = command.amount();
        this.fee = fee;
        this.currency = "XOF";
        this.status = status;
        this.failureReason = failureReason == null ? null : failureReason.name();
        this.occurredAt = occurredAt;
        this.recordedAt = recordedAt;
    }

    public static Transaction completed(String key, String hash, TransactionCommand command, long fee,
                                        Instant occurredAt, Instant recordedAt) {
        return new Transaction(key, hash, command, fee, TransactionStatus.COMPLETED, null, occurredAt, recordedAt);
    }

    public static Transaction failed(String key, String hash, TransactionCommand command, long fee,
                                     FailureReason reason, Instant occurredAt, Instant recordedAt) {
        return new Transaction(key, hash, command, fee, TransactionStatus.FAILED, reason, occurredAt, recordedAt);
    }

    /** Total debited from the source: amount + fee. */
    public long totalDebit() {
        return Math.addExact(amount, fee);
    }

    public boolean isCompleted() {
        return status == TransactionStatus.COMPLETED;
    }

    @PostLoad
    @PostPersist
    void markNotNew() {
        this.isNew = false;
    }

    @Override
    public boolean isNew() {
        return isNew;
    }

    @Override
    public UUID getId() { return id; }
    public String getIdempotencyKey() { return idempotencyKey; }
    public String getRequestHash() { return requestHash; }
    public TransactionType getType() { return type; }
    public TransactionStatus getStatus() { return status; }
    public UUID getSourceAccountId() { return sourceAccountId; }
    public UUID getDestinationAccountId() { return destinationAccountId; }
    public long getAmount() { return amount; }
    public long getFee() { return fee; }
    public String getCurrency() { return currency; }
    public String getFailureReason() { return failureReason; }
    public Instant getOccurredAt() { return occurredAt; }
    public Instant getRecordedAt() { return recordedAt; }
}
