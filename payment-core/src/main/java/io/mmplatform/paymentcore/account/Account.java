package io.mmplatform.paymentcore.account;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.Id;
import jakarta.persistence.PostLoad;
import jakarta.persistence.PostPersist;
import jakarta.persistence.Table;
import jakarta.persistence.Transient;
import jakarta.persistence.Version;
import java.time.Instant;
import java.util.Objects;
import java.util.UUID;
import org.springframework.data.domain.Persistable;

/**
 * A wallet. {@code balance} is a denormalised cache of the ledger entries
 * (see docs/adr/0002); it is only ever changed through {@link #debit} / {@link #credit},
 * always under a pessimistic row lock.
 */
@Entity
@Table(name = "accounts")
public class Account implements Persistable<UUID> {

    /**
     * Ids are generated by the application, so Spring Data cannot guess whether the
     * entity is new. Without this flag, save() would issue a useless SELECT (merge)
     * before every INSERT — measurable under load.
     */
    @Transient
    private boolean isNew = true;

    @Id
    private UUID id;

    @Column(nullable = false, unique = true, length = 20)
    private String phone;

    @Column(name = "owner_name", nullable = false, length = 120)
    private String ownerName;

    @Enumerated(EnumType.STRING)
    @Column(name = "account_type", nullable = false, length = 16)
    private AccountType type;

    @Enumerated(EnumType.STRING)
    @Column(nullable = false, length = 16)
    private AccountStatus status;

    @Column(nullable = false, length = 3)
    private String currency;

    @Column(nullable = false)
    private long balance;

    @Version
    private long version;

    @Column(name = "created_at", nullable = false, updatable = false)
    private Instant createdAt;

    @Column(name = "updated_at", nullable = false)
    private Instant updatedAt;

    /** Required by JPA. */
    protected Account() {}

    private Account(UUID id, String phone, String ownerName, AccountType type, Instant now) {
        this.id = id;
        this.phone = phone;
        this.ownerName = ownerName;
        this.type = type;
        this.status = AccountStatus.ACTIVE;
        this.currency = "XOF";
        this.balance = 0L;
        this.createdAt = now;
        this.updatedAt = now;
    }

    /** Opens a new, empty, active wallet. System accounts are created by migrations only. */
    public static Account open(String phone, String ownerName, AccountType type, Instant now) {
        if (type == AccountType.SYSTEM) {
            throw new IllegalArgumentException("System accounts cannot be opened through the API");
        }
        return new Account(UUID.randomUUID(), phone, ownerName, type, now);
    }

    /** Removes money from the wallet; returns the new balance. */
    public long debit(long amount, Instant now) {
        requirePositive(amount);
        if (!isSystem() && balance < amount) {
            // Callers check funds first; reaching this line is a programming error.
            throw new IllegalStateException("Insufficient funds on account " + id);
        }
        balance = Math.subtractExact(balance, amount);
        updatedAt = now;
        return balance;
    }

    /** Adds money to the wallet; returns the new balance. */
    public long credit(long amount, Instant now) {
        requirePositive(amount);
        balance = Math.addExact(balance, amount);
        updatedAt = now;
        return balance;
    }

    public void changeStatus(AccountStatus newStatus, Instant now) {
        this.status = Objects.requireNonNull(newStatus);
        this.updatedAt = now;
    }

    public boolean isSystem() {
        return type == AccountType.SYSTEM;
    }

    public boolean isActive() {
        return status == AccountStatus.ACTIVE;
    }

    /** True if the wallet can pay {@code total} XOF. System accounts can always pay. */
    public boolean canPay(long total) {
        return isSystem() || balance >= total;
    }

    private static void requirePositive(long amount) {
        if (amount <= 0) {
            throw new IllegalArgumentException("Amount must be positive, got " + amount);
        }
    }

    @PostLoad
    @PostPersist
    void markNotNew() {
        this.isNew = false;
    }

    @Override
    public boolean isNew() {
        return isNew;
    }

    @Override
    public UUID getId() { return id; }
    public String getPhone() { return phone; }
    public String getOwnerName() { return ownerName; }
    public AccountType getType() { return type; }
    public AccountStatus getStatus() { return status; }
    public String getCurrency() { return currency; }
    public long getBalance() { return balance; }
    public Instant getCreatedAt() { return createdAt; }
    public Instant getUpdatedAt() { return updatedAt; }
}
